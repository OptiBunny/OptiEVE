import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateRawSync } from 'node:zlib';
import { inspectPath, requirePublicSource } from './public-source.mjs';

const crcTable = Uint32Array.from({ length: 256 }, (_, value) => {
  for (let bit = 0; bit < 8; bit++) value = value & 1 ? 0xedb88320 ^ value >>> 1 : value >>> 1;
  return value >>> 0;
});
const crc32 = bytes => {
  let value = 0xffffffff;
  for (const byte of bytes) value = crcTable[(value ^ byte) & 255] ^ value >>> 8;
  return (value ^ 0xffffffff) >>> 0;
};

// Verify the small, non-ZIP64 archive generated by Git against captured inputs.
// This deliberately rejects formats/features we do not generate.
export function verifyPublicArchive(archive, entries) {
  const fail = () => { throw new Error('Public ZIP does not exactly match validated source'); };
  const end = archive.length - 22;
  if (end < 0 || archive.readUInt32LE(end) !== 0x06054b50) fail();
  if (archive.readUInt16LE(end + 4) || archive.readUInt16LE(end + 6) || archive.readUInt16LE(end + 20)) fail();
  const count = archive.readUInt16LE(end + 10);
  if (count === 0xffff || count !== archive.readUInt16LE(end + 8)) fail();
  const directoryStart = archive.readUInt32LE(end + 16);
  let cursor = directoryStart;
  let localEnd = 0;
  if (cursor + archive.readUInt32LE(end + 12) !== end) fail();
  const expected = new Map(entries.map(entry => [entry.name, entry.bytes]));
  const directories = new Set(entries.flatMap(({ name }) => name.split('/').slice(0, -1).map((_, index, parts) => parts.slice(0, index + 1).join('/') + '/')));
  const seen = new Set();
  const verifyExtra = extra => {
    // Git emits only the extended modification timestamp here, never UID/GID,
    // comments, paths, archive provenance, or arbitrary opaque extra fields.
    if (extra.length !== 9 || extra.readUInt16LE(0) !== 0x5455 || extra.readUInt16LE(2) !== 5 || extra[4] !== 1) fail();
  };
  for (let index = 0; index < count; index++) {
    if (cursor + 46 > end || archive.readUInt32LE(cursor) !== 0x02014b50) fail();
    const flags = archive.readUInt16LE(cursor + 8);
    const method = archive.readUInt16LE(cursor + 10);
    const compressed = archive.readUInt32LE(cursor + 20);
    const size = archive.readUInt32LE(cursor + 24);
    const crc = archive.readUInt32LE(cursor + 16);
    const nameLength = archive.readUInt16LE(cursor + 28);
    const extraLength = archive.readUInt16LE(cursor + 30);
    const commentLength = archive.readUInt16LE(cursor + 32);
    const offset = archive.readUInt32LE(cursor + 42);
    if (flags & ~0x800 || ![0, 8].includes(method) || commentLength || archive.readUInt16LE(cursor + 34)) fail();
    if ((archive.readUInt32LE(cursor + 38) >>> 16 & 0xf000) === 0xa000) fail();
    if (cursor + 46 + nameLength + extraLength > end) fail();
    const name = new TextDecoder('utf-8', { fatal: true }).decode(archive.subarray(cursor + 46, cursor + 46 + nameLength));
    const centralExtra = archive.subarray(cursor + 46 + nameLength, cursor + 46 + nameLength + extraLength);
    verifyExtra(centralExtra);
    if (seen.has(name)) fail();
    seen.add(name);
    const source = expected.get(name);
    if (!source && !directories.has(name)) fail();
    if (size !== (source?.length ?? 0) || offset !== localEnd || offset + 30 > directoryStart || archive.readUInt32LE(offset) !== 0x04034b50) fail();
    const localNameLength = archive.readUInt16LE(offset + 26);
    const localExtraLength = archive.readUInt16LE(offset + 28);
    const data = offset + 30 + localNameLength + localExtraLength;
    if (archive.readUInt16LE(offset + 6) !== flags || archive.readUInt16LE(offset + 8) !== method || data + compressed > directoryStart) fail();
    if (archive.readUInt32LE(offset + 14) !== crc || archive.readUInt32LE(offset + 18) !== compressed || archive.readUInt32LE(offset + 22) !== size) fail();
    if (archive.subarray(offset + 30, offset + 30 + localNameLength).toString('utf8') !== name) fail();
    const localExtra = archive.subarray(offset + 30 + localNameLength, data);
    verifyExtra(localExtra);
    if (!centralExtra.equals(localExtra)) fail();
    const packed = archive.subarray(data, data + compressed);
    const inflated = method === 8 ? inflateRawSync(packed, { maxOutputLength: size + 1, info: true }) : null;
    if (inflated && inflated.engine.bytesWritten !== packed.length) fail();
    const actual = inflated ? inflated.buffer : packed;
    if (!actual.equals(source ?? Buffer.alloc(0)) || crc32(actual) !== crc) fail();
    localEnd = data + compressed;
    cursor += 46 + nameLength + extraLength;
  }
  if (cursor !== end || localEnd !== directoryStart || [...expected.keys()].some(name => !seen.has(name))) fail();
}

export function createPublicArchive(root) {
  // Capture bytes once: uncommitted edits/deletions are respected, unlike HEAD.
  const entries = requirePublicSource(root);
  const temporary = mkdtempSync(join(tmpdir(), 'eve-public-source-'));
  const env = Object.fromEntries(Object.entries(process.env).filter(([name]) => !name.toUpperCase().startsWith('GIT_')));
  const git = (args, input) => execFileSync('git', [`--git-dir=${temporary}`, '-c', 'core.autocrlf=false', ...args], {
    env, input, stdio: ['pipe', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024,
  });
  try {
    git(['-c', 'init.templateDir=', 'init', '--bare', '--quiet', temporary]);
    mkdirSync(join(temporary, 'info'), { recursive: true });
    // Override local/global attributes that could drop or rewrite validated bytes.
    writeFileSync(join(temporary, 'info', 'attributes'), '* -export-ignore -export-subst -text -eol -crlf -filter -ident -working-tree-encoding\n');
    const index = [];
    for (const entry of entries) {
      const hash = git(['hash-object', '-w', '--stdin'], entry.bytes).toString().trim();
      index.push(`${entry.mode} ${hash}\t${entry.name}\0`);
    }
    git(['update-index', '-z', '--index-info'], index.join(''));
    const tree = git(['write-tree']).toString().trim();
    // A tree has no author/email/commit history. The current repository is untouched.
    const archive = git(['archive', '--format=zip', tree]);
    verifyPublicArchive(archive, entries);
    return { archive, files: entries.length, sha256: createHash('sha256').update(archive).digest('hex') };
  } finally {
    if (dirname(resolve(temporary)) !== resolve(tmpdir()) || !basename(temporary).startsWith('eve-public-source-')) throw new Error('Unexpected temporary archive directory');
    rmSync(temporary, { recursive: true, force: true });
  }
}

export function writePublicArchive(root) {
  const result = createPublicArchive(root);
  const directory = 'outputs/public-release';
  inspectPath(root, directory);
  mkdirSync(resolve(root, directory), { recursive: true });
  const name = 'OptiEVE-public-source.zip';
  const files = [['', result.archive], ['.sha256', `${result.sha256}  ${name}\n`]].map(([suffix, bytes]) => {
    const relative = `${directory}/${name}${suffix}`;
    const existing = inspectPath(root, relative);
    if (existing && !existing.isFile()) throw new Error('Public export destination must be a regular file');
    if (inspectPath(root, `${relative}.tmp`)) throw new Error('An unfinished public export already exists; inspect it before retrying');
    return { bytes, final: resolve(root, relative), temporary: resolve(root, `${relative}.tmp`) };
  });
  const staged = [];
  try {
    for (const file of files) {
      writeFileSync(file.temporary, file.bytes, { flag: 'wx' });
      staged.push(file);
    }
    for (const file of files) renameSync(file.temporary, file.final);
  } finally {
    for (const file of staged) rmSync(file.temporary, { force: true });
  }
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = writePublicArchive(resolve(dirname(fileURLToPath(import.meta.url)), '..'));
    console.log(`PASS: packaged and verified ${result.files} source files in outputs/public-release/OptiEVE-public-source.zip`);
    console.log(`SHA256: ${result.sha256}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
